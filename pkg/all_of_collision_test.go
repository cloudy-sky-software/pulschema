package pkg

import (
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	pschema "github.com/pulumi/pulumi/pkg/v3/codegen/schema"
)

// typeSpecRefs returns every Pulumi type ref used by the given
// type spec, including the ones nested in arrays, maps and unions.
func typeSpecRefs(ts *pschema.TypeSpec) []string {
	if ts == nil {
		return nil
	}

	refs := make([]string, 0)
	if strings.HasPrefix(ts.Ref, "#/types/") {
		refs = append(refs, ts.Ref)
	}

	refs = append(refs, typeSpecRefs(ts.Items)...)
	refs = append(refs, typeSpecRefs(ts.AdditionalProperties)...)

	for i := range ts.OneOf {
		refs = append(refs, typeSpecRefs(&ts.OneOf[i])...)
	}

	return refs
}

// typeFromRef returns the type that the given ref points to
// and fails the test if the type is not defined.
func typeFromRef(t *testing.T, pkg *pschema.PackageSpec, ref string) pschema.ComplexTypeSpec {
	t.Helper()

	tok := strings.TrimPrefix(ref, "#/types/")
	typeSpec, ok := pkg.Types[tok]
	require.Truef(t, ok, "Expected type %s to be defined", tok)

	return typeSpec
}

// resourcePropertyRef returns the type ref of the output property
// with the given name. It expects exactly one resource to have it.
func resourcePropertyRef(t *testing.T, pkg *pschema.PackageSpec, propName string) string {
	t.Helper()

	refs := make([]string, 0)
	for _, res := range pkg.Resources {
		prop, ok := res.Properties[propName]
		if !ok {
			continue
		}

		refs = append(refs, prop.Ref)
	}

	require.Lenf(t, refs, 1, "Expected exactly one resource with property %s", propName)
	require.NotEmpty(t, refs[0], "Expected property %s to be a type ref", propName)

	return refs[0]
}

// TestAllOfTypeNameCollision tests that the type generated for an
// allOf-wrapped resource property does not share its name with a
// schema in the components section, regardless of the order in which
// the two are processed.
//
// The spec has two pairs of resources, one for each order:
//   - machines (owns `lease`) is processed before leases (refs `Lease`).
//   - tokens (refs `Claim`) is processed before sessions (owns `claim`).
func TestAllOfTypeNameCollision(t *testing.T) {
	mustReadTestOpenAPIDoc(t, filepath.Join("testdata", "allof_collision_openapi.yml"))

	// Use a fresh package so that types generated by other
	// tests do not leak into this one.
	pkg := testPulumiPkg
	pkg.Types = map[string]pschema.ComplexTypeSpec{}
	pkg.Resources = map[string]pschema.ResourceSpec{}
	pkg.Functions = map[string]pschema.FunctionSpec{}

	openAPICtx := &OpenAPIContext{
		Doc: *testOpenAPIDoc,
		Pkg: &pkg,
	}

	csharpNamespaces := map[string]string{
		"": providerNamespace,
	}

	_, _, err := openAPICtx.GatherResourcesFromAPI(csharpNamespaces)
	require.NoError(t, err)

	t.Run("every type ref is defined", func(t *testing.T) {
		refs := make([]string, 0)
		for _, res := range pkg.Resources {
			for _, prop := range res.Properties {
				refs = append(refs, typeSpecRefs(&prop.TypeSpec)...)
			}

			for _, prop := range res.InputProperties {
				refs = append(refs, typeSpecRefs(&prop.TypeSpec)...)
			}
		}

		for _, typeSpec := range pkg.Types {
			for _, prop := range typeSpec.Properties {
				refs = append(refs, typeSpecRefs(&prop.TypeSpec)...)
			}
		}

		assert.NotEmpty(t, refs)

		for _, ref := range refs {
			assert.Containsf(t, pkg.Types, strings.TrimPrefix(ref, "#/types/"), "Dangling type ref %s", ref)
		}
	})

	t.Run("colliding schemas keep their own shape", func(t *testing.T) {
		// The properties owned by machines and sessions wrap the
		// stripped schemas, which do not have a nonce or version.
		for _, propName := range []string{"lease", "claim"} {
			owned := typeFromRef(t, &pkg, resourcePropertyRef(t, &pkg, propName))
			assert.Containsf(t, owned.Properties, "owner", "Property %s", propName)
			assert.NotContainsf(t, owned.Properties, "nonce", "Property %s", propName)
			assert.NotContainsf(t, owned.Properties, "version", "Property %s", propName)
		}

		// The properties that wrap the real schemas must have
		// everything the real schemas have.
		for _, propName := range []string{"data", "payload"} {
			referenced := typeFromRef(t, &pkg, resourcePropertyRef(t, &pkg, propName))
			assert.Containsf(t, referenced.Properties, "owner", "Property %s", propName)
			assert.Containsf(t, referenced.Properties, "nonce", "Property %s", propName)
			assert.Containsf(t, referenced.Properties, "version", "Property %s", propName)
		}
	})

	t.Run("non-colliding allOf type name is unchanged", func(t *testing.T) {
		ref := resourcePropertyRef(t, &pkg, "settings")
		assert.Truef(t, strings.HasSuffix(ref, ":Settings"), "Unexpected ref for settings: %s", ref)

		settings := typeFromRef(t, &pkg, ref)
		assert.Contains(t, settings.Properties, "region")
	})
}
